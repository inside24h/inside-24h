// Round 17 (critique f): the text audit over every item, variant, builder choice, cut and a broad set of comparisons
// (text-audit.ts). Every class of mistake must be empty; the dump is written for a reviewer to read.
import { describe, expect, it } from 'vitest';
// @ts-ignore (node types are not part of this app's tsconfig; vitest runs in node)
import { writeFileSync } from 'node:fs';
import { runAudit } from './text-audit';

const DUMP = new URL('../../../research/improvements/text-audit-2026-11-05.txt', import.meta.url);

describe('round 17: the text audit (every on-screen and posted string, every item, cut and a broad set of comparisons)', () => {
  it('no class of text mistake anywhere', () => {
    const res = runAudit(300);
    const byCls = new Map<string, string[]>();
    for (const i of res.issues) { const l = byCls.get(i.cls) ?? []; l.push(`${i.where}: ${i.text}`); byCls.set(i.cls, l); }
    const summary = [...byCls.entries()].map(([c, l]) => `${c}: ${l.length}`);
    const head = ['Inside 24h · text audit (round 17, 2026-11-05)', 'Generated by app/src/v4/text-audit.test.ts from the same code as the app (default body, first sip/bite at 22:00).',
      `Lint classes with findings: ${summary.length ? summary.join(', ') : 'none'}`, ...[...byCls.entries()].flatMap(([c, l]) => [`-- ${c}`, ...l.slice(0, 40).map((x) => `   ${x}`)])];
    try { writeFileSync(DUMP, [...head, ...res.dump, ''].join('\n'), 'utf8'); } catch { /* read-only checkout: the test still runs */ }
    expect(Object.fromEntries([...byCls.entries()].map(([c, l]) => [c, l.slice(0, 12)]))).toEqual({});
  }, 600_000);
});

import { resolveLink } from './deeplink';
import { servingPart } from './food/parse';
import { analyze } from './analyze';
import { parseMeal } from './food/parse';
import { sameAs } from './Compare';
import { teaseCard } from './video-plan';
import { AUDIT_PROFILE, auditCompare, auditSingle } from './text-audit';
import { shortName } from './video-story';

describe('round 17: the critic f findings, one by one', () => {
  const P = AUDIT_PROFILE, an = (q: string) => analyze(parseMeal(q), P);
  const same = (l: string, r: string) => { const L = parseMeal(l), R = sameAs(L[0], parseMeal(r)[0])!; return [analyze(L, P), analyze(R, P)] as const; };
  it('P0-1: a same-amount verdict says the amount once, with the bare names', () => {
    for (const [l, r] of [['apple juice', 'cola'], ['cola', 'orange juice']]) {
      const [a, b] = same(l, r), v = auditCompare(a, b, 'long').cp.verdict;
      expect(v).not.toMatch(/of \d+ ml of|\d+ ml of \d+ ml/);
      expect(v).toMatch(/the same amount of [a-z ]+ and [a-z ]+ hits your body about the same way\.$/);
    }
  });
  it('G-1: an answer that names a winner never sits next to "It’s close"', () => {
    const o = auditCompare(an('brie'), an('banana'), 'short');
    expect(o.cp.guess).toBeTruthy();
    if (!/^Almost the same/.test(o.cp.guess!.answer1)) expect(o.cp.verdict).not.toMatch(/^It’s close/);
  });
  it('G-2: no side shows a chapter long past at +24:00', () => {
    const o = auditCompare(an('brie'), an('banana'), 'short');
    for (const f of o.cp.plan.frames.filter((x) => x.stop === 1440 && x.beat === 'hold')) for (const t of [f.title, f.titleB]) expect(t ?? '').not.toMatch(/intestine|stomach|first/i);
  });
  it('G-3 / G-4 / G-8: hooks from the headline number, no "in 24 hours" twice, no water question for fish', () => {
    const brie = auditSingle(an('brie'), 'short', 'A'), brieB = auditSingle(an('brie'), 'short', 'B'), cod = auditSingle(an('cod'), 'long', 'B'), ice = auditSingle(an('ice cream'), 'medium', 'B');
    expect(brie.hook.line1).toMatch(/^Brie: \d+ g of fat\.$/);
    for (const h of [brie.hook, brieB.hook, cod.hook, ice.hook]) { expect(`${h.line1} ${h.line2}`).not.toMatch(/, in 24 hours|24 hours.*24 hours/); expect(`${h.line1} ${h.line2}`).not.toMatch(/water go/); }
    expect(brie.caps.tiktok).toMatch(/#brie\b/);
    expect(cod.name).toBe('Cod');
  });
  it('G-5: a builder burger is named by its add-ons; G-6: the after-meal slump is not "your sleep"', () => {
    const r = resolveLink('#q=hamburger&s=pljeskavica&on=bacon+patty+onion+mayo');
    const x = analyze(r.base.map((p) => servingPart(p.food, r.mult)), P);
    expect(shortName(x.label)).toMatch(/hamburger with bacon & extra patty/i);
    expect(shortName('1 hamburger with bacon, extra patty, onion and mayonnaise')).toBe('1 hamburger with bacon & extra patty'); // (the app's name, with its count)
    expect(teaseCard('Sleepy after eating')).toBe('Coming up: the after-meal slump.');
  });
  it('G-7: brie and cod end on a number', () => {
    expect(auditSingle(an('brie'), 'short', 'A').hero?.big).toMatch(/\d/);
    expect(auditSingle(an('cod'), 'long', 'A').hero?.big).toMatch(/\d/);
  });
  it('G-9: teaspoons come from the grams shown; P2-C / P2-CR / P2-OJ', () => {
    for (const q of ['muesli', 'banana', 'ice cream', 'orange juice']) {
      const t = auditSingle(an(q), 'long', 'A').plan.pages.map((p) => p.text).join(' ');
      const m = /(\d+) g of sugar: about (\d+) teaspoons?/.exec(t);
      if (m) expect(Number(m[2])).toBe(Math.round(Number(m[1]) / 4));
    }
    const cola = auditSingle(an('cola'), 'long', 'A').plan.pages.map((p) => p.text).join(' ');
    expect(cola).not.toMatch(/fruit sugar|40%/);
    const crepes = auditSingle(an('crepes with chocolate spread'), 'long', 'A').plan.pages.map((p) => p.text).join(' ');
    expect(crepes).not.toMatch(/Most of it is in your blood/);
    const [a, b] = same('cola', 'orange juice'), o = auditCompare(a, b, 'long');
    const first = o.cp.plan.pages.filter((p) => p.stop === 0).flatMap((p) => [p.text, p.textB ?? '']).join(' ');
    expect(first).not.toMatch(/g of sugar|teaspoons/);
  });
});
